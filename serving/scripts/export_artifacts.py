"""Package the files the API needs into ``serving/artifacts/`` (committed to git).

    python scripts/export_artifacts.py            # from data_pipeline/data/processed
    python scripts/export_artifacts.py --check    # verify the bundle against its manifest

Why: ``data_pipeline/data/`` is gitignored (it is regenerated by the notebooks), so a
fresh clone — GitHub Actions, a Docker build on Render or Railway — had nothing to
serve. This writes a ~6 MB bundle instead of the 30 MB pipeline folder:

* ``job_descriptions.csv`` and ``embeddings/`` (job + resume vectors and their indexes),
  copied as-is from Sprint 1;
* ``resumes_clean.csv.gz`` — ID, Category and the first ``--max-chars`` characters of
  each resume. MiniLM reads only the first ~256 word pieces (~1,100 characters), so
  the startup spot check and any re-encode give the same vectors as the full text;
* ``reference_profile.json`` — the drift baseline, built from the *full* texts;
* ``manifest.json`` — sha256 of every file, so CI can prove the bundle is intact.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

SERVING = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SERVING))
from app.monitoring import ReferenceProfile  # noqa: E402

DEFAULT_SRC = SERVING.parent / "data_pipeline" / "data" / "processed"
DEFAULT_DEST = SERVING / "artifacts"
COPY = ["job_descriptions.csv", "embeddings/job_embeddings.npy", "embeddings/job_index.csv",
        "embeddings/resume_embeddings.npy", "embeddings/resume_index.csv"]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def export(src: Path, dest: Path, model: str, max_chars: int, floor: float) -> dict:
    missing = [f for f in COPY + ["resumes_clean.csv"] if not (src / f).exists()]
    if missing:
        raise SystemExit(f"Missing in {src}: {missing}. Run preprocess.ipynb and embeddings.ipynb first.")
    (dest / "embeddings").mkdir(parents=True, exist_ok=True)
    for f in COPY:
        shutil.copy2(src / f, dest / f)

    resumes = pd.read_csv(src / "resumes_clean.csv", usecols=["ID", "Category", "clean_text"])
    slim = resumes.assign(clean_text=resumes["clean_text"].astype(str).str.slice(0, max_chars))
    # mtime=0 in the gzip header keeps the file byte-identical across re-exports.
    import gzip
    with gzip.GzipFile(dest / "resumes_clean.csv.gz", "wb", mtime=0) as gz:
        gz.write(slim.to_csv(index=False).encode("utf-8"))

    jobs = pd.read_csv(src / "job_descriptions.csv")
    profile = ReferenceProfile.build(
        model=model, categories=jobs["Category"].astype(str).tolist(),
        job_embeddings=np.load(src / "embeddings/job_embeddings.npy").astype(np.float32),
        cohort_embeddings=np.load(src / "embeddings/resume_embeddings.npy").astype(np.float32),
        text_lengths=resumes["clean_text"].astype(str).str.len().to_numpy(),
        similarity_floor=floor,
    )
    (dest / "reference_profile.json").write_text(profile.to_json())

    files = sorted(p for p in dest.rglob("*") if p.is_file() and p.name != "manifest.json")
    manifest = {
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "model": model,
        "resumes": len(resumes), "categories": len(jobs), "max_chars": max_chars,
        "reference": {"low_confidence_rate": profile.low_confidence_rate, "similarity_floor": floor},
        "files": {str(p.relative_to(dest)): {"sha256": sha256(p), "bytes": p.stat().st_size} for p in files},
    }
    (dest / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest


def check(dest: Path) -> list[str]:
    manifest = json.loads((dest / "manifest.json").read_text())
    problems = []
    for name, meta in manifest["files"].items():
        p = dest / name
        if not p.exists():
            problems.append(f"missing: {name}")
        elif sha256(p) != meta["sha256"]:
            problems.append(f"changed: {name}")
    return problems


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--dest", type=Path, default=DEFAULT_DEST)
    ap.add_argument("--model", default="all-MiniLM-L6-v2")
    ap.add_argument("--max-chars", type=int, default=3000)
    ap.add_argument("--similarity-floor", type=float, default=0.35)
    ap.add_argument("--check", action="store_true", help="verify an existing bundle and exit")
    a = ap.parse_args()
    if a.check:
        problems = check(a.dest)
        print("\n".join(problems) or f"OK: {a.dest} matches manifest.json")
        raise SystemExit(1 if problems else 0)
    m = export(a.src, a.dest, a.model, a.max_chars, a.similarity_floor)
    total = sum(f["bytes"] for f in m["files"].values())
    print(f"Wrote {len(m['files'])} files ({total / 1e6:.1f} MB) to {a.dest}")
    print(f"Reference: {m['resumes']} resumes, {m['categories']} categories, "
          f"{m['reference']['low_confidence_rate']:.1%} below the {a.similarity_floor} floor")


if __name__ == "__main__":
    main()
